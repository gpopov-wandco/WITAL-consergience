"""``concierge setup``: first-run wizard.

Implements: F28, F19, C3

Generates the master key, signing key, backup key and metrics token, writes ``.env``
(never committed, mode 0600 where the platform supports it), migrates the database,
creates the operator account with a one-time admin link, optionally creates the first
tenant from a profile file and finally runs ``concierge doctor`` when available.
Secrets are printed exactly once: the admin link. Keys never leave the ``.env`` file.
"""

from __future__ import annotations

import asyncio
import base64
import json
import os
import secrets
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import timedelta
from pathlib import Path

import yaml
from dotenv import dotenv_values
from sqlalchemy import select

from concierge import audit
from concierge.clock import Clock, SystemClock
from concierge.db.migrate import upgrade
from concierge.db.models import SystemSetting, User
from concierge.db.session import Database
from concierge.security.sessions import hash_token
from concierge.settings import Settings, reset_settings_cache
from concierge.tenants.profile import TenantProfile
from concierge.tenants.service import TenantService

BOOTSTRAP_TTL = timedelta(hours=24)
BOOTSTRAP_SETTING = "bootstrap_admin"


@dataclass
class SetupResult:
    env_path: Path
    database_url: str
    admin_link: str | None
    tenant_slug: str | None
    notes: list[str] = field(default_factory=list)


def generate_env_values() -> dict[str, str]:
    master = base64.b64encode(secrets.token_bytes(32)).decode("ascii")
    return {
        "GC_MASTER_KEYS": json.dumps({"k1": master}),
        "GC_ACTIVE_KEY_ID": "k1",
        "GC_SIGNING_KEY": secrets.token_urlsafe(48),
        "GC_BACKUP_KEY": base64.b64encode(secrets.token_bytes(32)).decode("ascii"),
        "GC_METRICS_TOKEN": secrets.token_urlsafe(32),
    }


def read_env(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    return {k: v for k, v in dotenv_values(path, encoding="utf-8").items() if v is not None}


def _quote(value: str) -> str:
    if not any(ch in value for ch in " #\"'$\\"):
        return value
    if "'" not in value:
        return f"'{value}'"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def write_env(path: Path, values: dict[str, str]) -> None:
    lines = ["# Generated by `concierge setup`. Keep this file out of git; back it up encrypted."]
    lines.extend(f"{key}={_quote(value)}" for key, value in values.items())
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    if os.name == "posix":
        os.chmod(path, 0o600)


def _apply_env(values: dict[str, str]) -> None:
    for key, value in values.items():
        os.environ[key] = value
    reset_settings_cache()


def _prepare_values(
    existing: dict[str, str],
    *,
    force: bool,
    non_interactive: bool,
    database_url: str | None,
    public_base_url: str | None,
    operator_email: str | None,
    prompt: Callable[[str, str], str] | None,
) -> dict[str, str]:
    values = {} if force else dict(existing)
    for key, value in generate_env_values().items():
        values.setdefault(key, value)
    values.setdefault("GC_ENV", "development")
    values.setdefault("PYTHONUTF8", "1")
    ask = prompt if (prompt is not None and not non_interactive) else None
    if database_url:
        values["GC_DATABASE_URL"] = database_url
    elif ask is not None and not values.get("GC_DATABASE_URL"):
        answer = ask("Database URL (empty for the default SQLite file)", "")
        if answer:
            values["GC_DATABASE_URL"] = answer
    if public_base_url:
        values["GC_PUBLIC_BASE_URL"] = public_base_url
    elif ask is not None and not values.get("GC_PUBLIC_BASE_URL"):
        values["GC_PUBLIC_BASE_URL"] = ask("Public base URL (https://...)", "http://127.0.0.1:8000")
    if operator_email:
        values["GC_OPERATOR_EMAIL"] = operator_email
    elif ask is not None and not values.get("GC_OPERATOR_EMAIL"):
        values["GC_OPERATOR_EMAIL"] = ask("Operator e-mail for alerts", "")
    return values


async def run_setup(
    *,
    env_path: Path,
    non_interactive: bool,
    database_url: str | None = None,
    public_base_url: str | None = None,
    operator_email: str | None = None,
    tenant_profile: Path | None = None,
    force: bool = False,
    clock: Clock | None = None,
    echo: Callable[[str], None] = lambda _s: None,
    prompt: Callable[[str, str], str] | None = None,
) -> SetupResult:
    clock = clock or SystemClock()
    existing = await asyncio.to_thread(read_env, env_path)
    if existing and not force:
        echo(f"{env_path} exists; keeping its keys and filling only missing values")
    values = _prepare_values(
        existing,
        force=force,
        non_interactive=non_interactive,
        database_url=database_url,
        public_base_url=public_base_url,
        operator_email=operator_email,
        prompt=prompt,
    )
    await asyncio.to_thread(write_env, env_path, values)
    _apply_env(values)
    settings = Settings(_env_file=env_path)
    url = settings.database_url()
    if url.startswith("sqlite+aiosqlite:///"):
        parent = Path(url.removeprefix("sqlite+aiosqlite:///")).parent
        await asyncio.to_thread(parent.mkdir, parents=True, exist_ok=True)
    db = Database(url)
    notes: list[str] = []
    slug: str | None = None
    try:
        await upgrade(db.engine)
        echo("database migrated to head")
        admin_link = await _bootstrap_operator(
            db, settings, clock, values.get("GC_OPERATOR_EMAIL", "")
        )
        service = TenantService(db, clock)
        if tenant_profile is not None:
            text = await asyncio.to_thread(tenant_profile.read_text, encoding="utf-8")
            profile = TenantProfile.model_validate(yaml.safe_load(text))
            if await service.get(profile.slug) is None:
                await service.create(profile, actor="setup")
                echo(f"tenant {profile.slug} created")
            else:
                echo(f"tenant {profile.slug} already exists")
            slug = profile.slug
        elif prompt is not None and not non_interactive:
            slug_answer = prompt("First tenant slug (empty to skip)", "")
            if slug_answer:
                name = prompt("Hotel name", slug_answer.replace("-", " ").title())
                tz = prompt("Time zone", "Europe/Berlin")
                await service.create(
                    TenantProfile(slug=slug_answer, name=name, timezone=tz, status="pilot"),
                    actor="setup",
                )
                slug = slug_answer
    finally:
        await db.dispose()
    return SetupResult(
        env_path=env_path, database_url=url, admin_link=admin_link, tenant_slug=slug, notes=notes
    )


async def _bootstrap_operator(
    db: Database, settings: Settings, clock: Clock, email: str
) -> str | None:
    """Create the operator account (once) and a single-use bootstrap link."""
    async with db.scope() as session:
        operator = await session.scalar(
            select(User).where(User.role == "operator").order_by(User.created_at)
        )
        if operator is None:
            address = email or "operator@localhost"
            operator = User(
                tenant_id=None,
                email=address,
                email_lower=address.lower(),
                name="Operator",
                role="operator",
                locale="de",
            )
            session.add(operator)
            await session.flush()
        if operator.password_hash:
            return None
        token = secrets.token_urlsafe(32)
        setting = await session.get(SystemSetting, BOOTSTRAP_SETTING)
        payload = {
            "token_hash": hash_token(token),
            "user_id": operator.id,
            "expires_at": (clock.now() + BOOTSTRAP_TTL).isoformat(),
        }
        if setting is None:
            session.add(SystemSetting(key=BOOTSTRAP_SETTING, value=payload))
        else:
            setting.value = payload
        audit.record(session, actor="setup", action="operator.bootstrap_link", target=operator.id)
        await session.commit()
    return f"{settings.public_base_url()}/admin/bootstrap/{token}"
